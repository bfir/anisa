export function translate(language, key, params = {}) {
  const index = Object.keys(languages).indexOf(language);
  const text = messages[key]?.[index < 0 ? 0 : index] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}
